"""Turn a BepInEx log from a live run into docs/03-input-map.md.

The plugin logs the full InControl action map at world load. This script parses that block
so the document is generated from evidence rather than transcribed by hand.

Usage:
    python tools\\gen_input_map.py
    python tools\\gen_input_map.py --log "path\\to\\LogOutput.log" --out docs\\03-input-map.md
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

DEFAULT_LOG = Path(r"C:\GOG Games\Cloudpunk\BepInEx\LogOutput.log")
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "03-input-map.md"

# The actions the co-op mod must be able to drive on the car host's behalf, grouped by role.
GROUPS: list[tuple[str, list[str]]] = [
    ("Driving (car host must synthesise these)", [
        "DriveForward", "DriveBackward", "SteerLeft", "SteerRight",
        "Ascend", "Sink", "StrafeLeft", "StrafeRight",
    ]),
    ("Camera", [
        "CameraCockpit", "CameraLeft", "CameraRight", "CameraUp", "CameraDown",
        "CameraUnlock", "ControlsFullMap", "ControlsDisableHUD",
    ]),
    ("On foot", [
        "MoveUp", "MoveDown", "MoveLeft", "MoveRight", "Sneak", "Interact",
        "Cancel", "Inventory",
    ]),
    ("UI / menu", [
        "SkipDialog", "ControlsMenu", "ControllerConfirm", "Left", "Right", "Up", "Down",
        "MouseSubmit", "MouseCheck", "MousePointer", "MouseButtons",
        "ScrollUp", "ScrollDown", "CameraZoomUp", "CameraZoomDown",
        "ScrollMapUp", "ScrollMapDown",
        "FullMapLeft", "FullMapRight", "FullMapUp", "FullMapDown",
        "RotateCameraLeft", "RotateCameraRight", "ControllerCheck",
    ]),
]

ROW_RE = re.compile(r"^\s*(\w+)\s+<-\s(.*)$")
# BepInEx prefixes every logged line with "[Info   :Source] ".
PREFIX_RE = re.compile(r"^\[[^\]]*\]\s?")


def strip_prefix(line: str) -> str:
    return PREFIX_RE.sub("", line.rstrip())


def parse_log(text: str) -> dict[str, str]:
    actions: dict[str, str] = {}
    inside = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if "---- input map" in line:
            inside = True
            continue
        if inside and set(line.strip()) <= {"-"} and line.strip():
            break
        if not inside:
            continue
        match = ROW_RE.match(strip_prefix(line))
        if match:
            actions[match.group(1)] = match.group(2).strip()
    return actions


def parse_activity(text: str) -> dict[str, tuple[str, str]]:
    activity: dict[str, tuple[str, str]] = {}
    inside = False
    for raw in text.splitlines():
        line = raw.rstrip()
        if "---- action activity" in line:
            inside = True
            activity = {}
            continue
        if inside and set(line.strip()) <= {"-"} and line.strip():
            inside = False
            continue
        if not inside:
            continue
        parts = strip_prefix(line)
        match = re.match(r"^\s*(\w+)\s+(\S+)\s+\.\.\s+(\S+)\s*$", parts)
        if match:
            activity[match.group(1)] = (match.group(2), match.group(3))
    return activity


def cell(bindings: str) -> str:
    """Escape pipes so a multi-binding value does not break the markdown table."""
    return bindings.replace("|", "\\|")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--log", type=Path, default=DEFAULT_LOG)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    if not args.log.is_file():
        print(f"log not found: {args.log}")
        return 2

    text = args.log.read_text(encoding="utf-8", errors="replace")
    actions = parse_log(text)
    if not actions:
        print("no input map block in the log; run the game once with the plugin deployed")
        return 2
    activity = parse_activity(text)

    lines: list[str] = []
    add = lines.append
    add("# Cloudpunk input map")
    add("")
    add("Generated by `tools/gen_input_map.py` from a live `BepInEx\\LogOutput.log` run.")
    add("Source: `GameInput.Instance.playerActions` (a `PlayerActions : PlayerActionSet` read")
    add("through `PlayerActionSet.actions`, with every `BindingSource.Name`).")
    add("")
    add(f"**{len(actions)} actions.**")
    add("")

    listed: set[str] = set()
    for title, names in GROUPS:
        present = [n for n in names if n in actions]
        listed.update(present)
        add(f"## {title}")
        add("")
        add("| Action | Default bindings |")
        add("| --- | --- |")
        for name in present:
            add(f"| `{name}` | {cell(actions[name])} |")
        add("")

    rest = sorted(set(actions) - listed)
    if rest:
        add("## Not yet classified")
        add("")
        add("| Action | Default bindings |")
        add("| --- | --- |")
        for name in rest:
            add(f"| `{name}` | {cell(actions[name])} |")
        add("")

    if activity:
        add("## Observed activity")
        add("")
        add("min..max per action since the world loaded, from the most recent run. Only")
        add("mouse-driven actions moved because that run had no one at the keyboard.")
        add("")
        add("| Action | min | max |")
        add("| --- | --- | --- |")
        for name, (low, high) in sorted(activity.items()):
            add(f"| `{name}` | {low} | {high} |")
        add("")

    add("## Why this matters")
    add("")
    add("Iteration 4 injects a remote player's control by feeding these named actions from a")
    add("virtual InControl device on the car host. The eight driving actions are all")
    add("`PlayerAction` entries on one `PlayerActionSet`, reachable by name through")
    add("`PlayerActionSet.actionsByName`, so no vehicle code has to be patched.")
    add("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(actions)} actions, {len(activity)} observed -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
